document.addEventListener("DOMContentLoaded", () => {
    const body = document.body;
    const root = document.documentElement;
    const mobileToggle = document.querySelector(".mobile-toggle");
    const sidebar = document.querySelector(".sidebar");
    const navLinks = document.querySelectorAll(".sidebar-menu a");
    const sections = document.querySelectorAll("section[id]");
    const revealItems = document.querySelectorAll(".reveal");
    const langButtons = document.querySelectorAll(".lang-btn");
    const translatableNodes = document.querySelectorAll("[data-i18n]");
    const metaDescription = document.querySelector('meta[name="description"]');
    const tiltCards = document.querySelectorAll(".tilt-card");
    const contactForm = document.getElementById("contactForm");
    const contactFields = document.querySelector(".contact-fields");
    const successMessage = document.getElementById("successMessage");

    const applyLanguage = (lang) => {
        const dictionary = translations[lang] || translations.en;

        translatableNodes.forEach((node) => {
            const key = node.dataset.i18n;
            if (dictionary[key]) {
                node.textContent = dictionary[key];
            }
        });

        document.title = lang === "zh"
            ? "Lin Zhi | 业务流程自动化与数字化转型"
            : "Lin Zhi | Business Process Automation & Digital Transformation";

        if (metaDescription) {
            metaDescription.setAttribute(
                "content",
                lang === "zh"
                    ? "Lin Zhi 帮助组织通过技术驱动的解决方案改善运营、简化流程并创造可衡量的业务价值。"
                    : "Lin Zhi helps organisations improve operations, simplify processes and create measurable business value through technology-enabled solutions."
            );
        }

        root.lang = lang === "zh" ? "zh-CN" : "en";

        langButtons.forEach((button) => {
            button.classList.toggle("is-active", button.dataset.lang === lang);
        });

        localStorage.setItem("portfolio-language", lang);
    };

    const storedLanguage = localStorage.getItem("portfolio-language");
    applyLanguage(translations[storedLanguage] ? storedLanguage : "en");

    const setMenuState = (isOpen) => {
        if (!mobileToggle) return;
        mobileToggle.setAttribute("aria-expanded", String(isOpen));
        body.classList.toggle("menu-open", isOpen);
    };

    if (mobileToggle) {
        mobileToggle.addEventListener("click", () => {
            const isOpen = mobileToggle.getAttribute("aria-expanded") === "true";
            setMenuState(!isOpen);
        });
    }

    navLinks.forEach((link) => {
        link.addEventListener("click", () => {
            if (window.innerWidth <= 920) {
                setMenuState(false);
            }
        });
    });

    document.addEventListener("click", (event) => {
        if (!body.classList.contains("menu-open") || !sidebar || !mobileToggle) return;
        if (!sidebar.contains(event.target) && !mobileToggle.contains(event.target)) {
            setMenuState(false);
        }
    });

    document.addEventListener("keydown", (event) => {
        if (event.key === "Escape") setMenuState(false);
    });

    langButtons.forEach((button) => {
        button.addEventListener("click", () => applyLanguage(button.dataset.lang));
    });

    const sectionObserver = new IntersectionObserver(
        (entries) => {
            entries.forEach((entry) => {
                if (!entry.isIntersecting) return;
                const currentId = entry.target.getAttribute("id");
                navLinks.forEach((link) => {
                    link.classList.toggle("active", link.getAttribute("href") === `#${currentId}`);
                });
            });
        },
        { rootMargin: "-36% 0px -45% 0px", threshold: 0.08 }
    );

    sections.forEach((section) => sectionObserver.observe(section));

    const revealObserver = new IntersectionObserver(
        (entries, observer) => {
            entries.forEach((entry) => {
                if (!entry.isIntersecting) return;
                entry.target.classList.add("is-visible");
                observer.unobserve(entry.target);
            });
        },
        { threshold: 0.14, rootMargin: "0px 0px -48px 0px" }
    );

    revealItems.forEach((item) => revealObserver.observe(item));

    const updateScrollProgress = () => {
        const scrollable = document.documentElement.scrollHeight - window.innerHeight;
        const progress = scrollable > 0 ? (window.scrollY / scrollable) * 100 : 0;
        root.style.setProperty("--scroll-progress", `${Math.min(progress, 100)}%`);
    };

    updateScrollProgress();
    window.addEventListener("scroll", updateScrollProgress, { passive: true });
    window.addEventListener("resize", updateScrollProgress);

    document.addEventListener("pointermove", (event) => {
        const x = `${(event.clientX / window.innerWidth) * 100}%`;
        const y = `${(event.clientY / window.innerHeight) * 100}%`;
        root.style.setProperty("--glow-x", x);
        root.style.setProperty("--glow-y", y);
    });

    tiltCards.forEach((card) => {
        card.addEventListener("pointermove", (event) => {
            const rect = card.getBoundingClientRect();
            const x = event.clientX - rect.left;
            const y = event.clientY - rect.top;
            const rotateY = ((x / rect.width) - 0.5) * 8;
            const rotateX = ((y / rect.height) - 0.5) * -8;
            card.style.transform = `perspective(1200px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateY(-4px)`;
        });

        card.addEventListener("pointerleave", () => {
            card.style.transform = "";
        });
    });

    if (contactForm) {
        contactForm.addEventListener("submit", (event) => {
            event.preventDefault();
            if (contactFields && successMessage) {
                contactFields.classList.add("hidden");
                successMessage.classList.remove("hidden");
            }
        });
    }
});